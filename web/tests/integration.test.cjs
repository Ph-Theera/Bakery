const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const enabled = process.env.TEST_LIVE_API === 'true';
test('frontend client -> disposable Go/PostgreSQL API checkout and admin flow', { skip: !enabled }, async () => {
  process.env.NEXT_PUBLIC_API_MOCK = 'false';
  process.env.NEXT_PUBLIC_API_BASE_URL = 'http://localhost:8080/api/v1';
  require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, filename);
  const storage = new Map();
  global.window = { sessionStorage: { getItem: k => storage.get(k) || null, setItem: (k, v) => storage.set(k, v) } };
  const { api } = require('../lib/api.ts');
  const { setAdminToken } = require('../lib/auth.ts');
  const products = await api.products();
  const product = products.find(p => p.slug === 'integration-bread');
  assert.ok(product, 'disposable seed required; do not run against a real store');
  assert.ok((await api.categories()).length);
  assert.equal((await api.store()).store_name, 'TongBai');
  const payload = { customer: { name: 'Integration Test', phone: '0812345678' }, fulfillment: { type: 'delivery', address: 'Test address only' }, items: [{ productId: product.id, quantity: 2 }], paymentMethod: 'bank_transfer' };
  assert.equal((await api.quote(payload)).total_thb, 250);
  const key = crypto.randomUUID();
  const order = await api.createOrder(payload, key);
  assert.equal((await api.createOrder(payload, key)).id, order.id);
  assert.equal((await api.orders())[0].id, order.id);
  const png = new File([Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jBqkAAAAASUVORK5CYII=', 'base64')], 'test.png', { type: 'image/png' });
  await api.uploadPaymentSlip(order.payment_id, png, order.id);
  await api.submitPayment(order.payment_id, order.id);
  assert.equal((await api.order(order.id)).payment_status, 'submitted');
  setAdminToken('integration-admin-only');
  assert.equal((await api.paymentSlip(order.payment_id)).type, 'image/png');
  await api.approvePayment(order.payment_id);
  await api.approvePayment(order.payment_id);
  assert.equal((await api.order(order.id)).order_status, 'confirmed');
  assert.equal((await api.product(product.slug)).stock_quantity, 8);
  await api.updateOrderStatus(order.id, 'preparing');
  await api.updateOrderStatus(order.id, 'shipped');
  await api.updateOrderStatus(order.id, 'completed');
  await api.updateOrder(order.id, { internal_note: 'integration review only' });
  assert.ok((await api.customers()).length);
  assert.ok((await api.adminDashboard()).total_orders);
  const settings = await api.settings();
  await api.updateSettings({ ...settings, description: 'Integration verified' });
  const created = await api.createProduct({ category_id: product.category_id, name: 'Admin Test', slug: 'admin-test-' + Date.now(), description_th: '', price_thb: 25, stock_quantity: 1, is_active: true, is_featured: false });
  await api.updateProduct(created.id, { stock_quantity: 0, is_active: false });
  await api.deleteProduct(created.id);
  const preflight = await fetch('http://localhost:8080/api/v1/orders', { method: 'OPTIONS', headers: { Origin: 'http://localhost:3000', 'Access-Control-Request-Headers': 'Authorization,Idempotency-Key' } });
  assert.equal(preflight.headers.get('Access-Control-Allow-Origin'), 'http://localhost:3000');
  const html = await (await fetch('http://localhost:3000')).text();
  assert.ok(html.includes('Integration Bread'), 'SSR storefront must show DB product, not mock');
  for (const path of ['/admin', '/checkout', '/orders', '/products/integration-bread']) {
    assert.equal((await fetch('http://localhost:3000' + path)).status, 200);
  }
});
